export function detectBrowserLanguage(): 'es' | 'en' | 'fr' | 'de' | 'pt' {
  const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('focusguard_lang') : null;
  if (saved && ['es', 'en', 'fr', 'de', 'pt'].includes(saved)) {
    return saved as any;
  }

  const browserLangs: string[] = [];
  if (typeof navigator !== 'undefined') {
    if (Array.isArray(navigator.languages) && navigator.languages.length > 0) {
      browserLangs.push(...navigator.languages);
    }
    if (navigator.language) {
      browserLangs.push(navigator.language);
    }
    if ((navigator as any).userLanguage) {
      browserLangs.push((navigator as any).userLanguage);
    }
  }

  for (const rawLang of browserLangs) {
    if (!rawLang) continue;
    const lang = rawLang.toLowerCase();
    if (lang.startsWith('es')) return 'es';
    if (lang.startsWith('fr')) return 'fr';
    if (lang.startsWith('de')) return 'de';
    if (lang.startsWith('pt')) return 'pt';
    if (lang.startsWith('en')) return 'en';
  }

  return 'es';
}

export function applyTranslations() {
  const userLang = detectBrowserLanguage();
  const dict = translations[userLang] || translations.en;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key && (dict as any)[key]) {
      if (el.tagName === 'TITLE') {
        document.title = (dict as any)[key];
      } else if (el.tagName === 'INPUT' && (el as HTMLInputElement).hasAttribute('placeholder')) {
        (el as HTMLInputElement).placeholder = (dict as any)[key];
      } else {
        el.innerHTML = (dict as any)[key];
      }
    }
  });
  
  document.documentElement.lang = userLang;
  return dict;
}


